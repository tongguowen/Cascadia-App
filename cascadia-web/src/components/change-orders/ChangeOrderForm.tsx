import { useForm } from '@tanstack/react-form'
import { useState } from 'react'
import { useTranslation } from 'react-i18next'
import { changeOrderSchema } from '@cascadia/commons/items/types/change-order'
import type { ChangeOrder } from '@cascadia/commons/items/types/change-order'
import { AttributesEditor } from '@/components/items/AttributesEditor'
import { getItemNumberHelpText } from '@/items/numbering/format'
import { zodValidator } from '@/form-validation'
import {
  Button,
  Checkbox,
  FormField,
  Input,
  Label,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
  Textarea,
} from '@/components/ui'

interface ChangeOrderFormProps {
  changeOrder?: Partial<ChangeOrder>
  onSubmit: (data: ChangeOrder) => void | Promise<void>
  onCancel?: () => void
  isSubmitting?: boolean
}

export function ChangeOrderForm({
  changeOrder,
  onSubmit,
  onCancel,
  isSubmitting,
}: ChangeOrderFormProps) {
  const { t: tc } = useTranslation('common')
  const { t: tp } = useTranslation('pages')
  const [attributes, setAttributes] = useState<Record<string, unknown>>(
    changeOrder?.attributes ?? {},
  )
  const form = useForm({
    defaultValues: {
      itemType: 'ChangeOrder' as const,
      changeType: 'ECO' as const,
      priority: 'medium' as const,
      itemNumber: '',
      name: '',
      reasonForChange: '',
      impactDescription: '',
      implementationDate: '',
      isBaseline: false,
      baselineName: '',
      ...changeOrder,
    },
    validators: {
      onSubmit: zodValidator(changeOrderSchema),
    },
    onSubmit: async ({ value }) => {
      // Convert empty strings to undefined for optional fields
      // Zod's .optional() allows undefined but not empty strings
      const submissionData = {
        ...value,
        itemNumber: value.itemNumber.trim() || undefined,
        name: value.name.trim() || undefined,
        reasonForChange: value.reasonForChange.trim() || undefined,
        impactDescription: value.impactDescription.trim() || undefined,
        implementationDate: value.implementationDate || undefined,
        baselineName: value.baselineName.trim() || undefined,
        attributes,
      } as ChangeOrder
      await onSubmit(submissionData)
    },
  })

  return (
    <form
      onSubmit={(e) => {
        e.preventDefault()
        e.stopPropagation()
        form.handleSubmit()
      }}
      className="space-y-6"
      data-testid="change-order-form"
    >
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {/* Item Number - Always auto-generated for Change Orders */}
        <FormField
          label={tc('fields.changeOrderNumber')}
          helpText={getItemNumberHelpText('ChangeOrder')}
        >
          <div className="flex items-center h-10 px-3 rounded-md border border-input bg-muted text-muted-foreground">
            {tc('labels.autoGeneratedOnCreation')}
          </div>
        </FormField>

        {/* Name */}
        <form.Field name="name">
          {(field) => (
            <FormField
              label={tc('fields.name')}
              error={field.state.meta.errors[0]}
              className="md:col-span-2"
              helpText={tp('changeOrders.form.nameHelp')}
            >
              <Input
                name={field.name}
                value={field.state.value}
                onChange={(e) => field.handleChange(e.target.value)}
                onBlur={field.handleBlur}
                placeholder={tp('changeOrders.form.namePlaceholder')}
                error={!!field.state.meta.errors.length}
                data-testid="change-order-name"
              />
            </FormField>
          )}
        </form.Field>

        {/* Change Type */}
        <form.Field name="changeType">
          {(field) => (
            <FormField
              label={tc('fields.changeType')}
              required
              error={field.state.meta.errors[0]}
              helpText={tp('changeOrders.form.changeTypeHelp')}
            >
              <Select
                value={field.state.value}
                onValueChange={(value) =>
                  field.handleChange(
                    value as 'ECO' | 'ECN' | 'MCO' | 'Deviation' | 'XCO',
                  )
                }
              >
                <SelectTrigger error={!!field.state.meta.errors.length}>
                  <SelectValue placeholder={tc('labels.selectType')} />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="ECO">
                    {tp('changeOrders.form.changeTypeEco')}
                  </SelectItem>
                  <SelectItem value="ECN">
                    {tp('changeOrders.form.changeTypeEcn')}
                  </SelectItem>
                  <SelectItem value="MCO">
                    {tp('changeOrders.form.changeTypeMco')}
                  </SelectItem>
                  <SelectItem value="Deviation">
                    {tp('changeOrders.form.changeTypeDeviation')}
                  </SelectItem>
                  <SelectItem value="XCO">
                    {tp('changeOrders.form.changeTypeXco')}
                  </SelectItem>
                </SelectContent>
              </Select>
            </FormField>
          )}
        </form.Field>

        {/* Priority */}
        <form.Field name="priority">
          {(field) => (
            <FormField
              label={tc('fields.priority')}
              error={field.state.meta.errors[0]}
              helpText={tp('changeOrders.form.priorityHelp')}
            >
              <Select
                value={field.state.value}
                onValueChange={(value) =>
                  field.handleChange(
                    value as 'low' | 'medium' | 'high' | 'critical',
                  )
                }
              >
                <SelectTrigger error={!!field.state.meta.errors.length}>
                  <SelectValue placeholder={tc('labels.selectPriority')} />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="low">
                    {tp('changeOrders.form.priorityLow')}
                  </SelectItem>
                  <SelectItem value="medium">
                    {tp('changeOrders.form.priorityMedium')}
                  </SelectItem>
                  <SelectItem value="high">
                    {tp('changeOrders.form.priorityHigh')}
                  </SelectItem>
                  <SelectItem value="critical">
                    {tp('changeOrders.form.priorityCritical')}
                  </SelectItem>
                </SelectContent>
              </Select>
            </FormField>
          )}
        </form.Field>

        {/* Reason for Change */}
        <form.Field name="reasonForChange">
          {(field) => (
            <FormField
              label={tc('fields.reasonForChange')}
              error={field.state.meta.errors[0]}
              className="md:col-span-2"
              helpText={tp('changeOrders.form.reasonHelp')}
            >
              <Textarea
                name={field.name}
                value={field.state.value}
                onChange={(e) => field.handleChange(e.target.value)}
                onBlur={field.handleBlur}
                placeholder={tp('changeOrders.form.reasonPlaceholder')}
                rows={4}
                error={!!field.state.meta.errors.length}
              />
            </FormField>
          )}
        </form.Field>

        {/* Impact Description */}
        <form.Field name="impactDescription">
          {(field) => (
            <FormField
              label={tc('fields.impactDescription')}
              error={field.state.meta.errors[0]}
              className="md:col-span-2"
              helpText={tp('changeOrders.form.impactHelp')}
            >
              <Textarea
                name={field.name}
                value={field.state.value}
                onChange={(e) => field.handleChange(e.target.value)}
                onBlur={field.handleBlur}
                placeholder={tp('changeOrders.form.impactPlaceholder')}
                rows={4}
                error={!!field.state.meta.errors.length}
              />
            </FormField>
          )}
        </form.Field>

        {/* Implementation Date */}
        <form.Field name="implementationDate">
          {(field) => (
            <FormField
              label={tc('fields.implementationDate')}
              error={field.state.meta.errors[0]}
              helpText={tp('changeOrders.form.implementationHelp')}
            >
              <Input
                name={field.name}
                value={
                  field.state.value instanceof Date
                    ? field.state.value.toISOString().split('T')[0]
                    : (field.state.value ?? '')
                }
                onChange={(e) => field.handleChange(e.target.value)}
                onBlur={field.handleBlur}
                type="date"
                error={!!field.state.meta.errors.length}
              />
            </FormField>
          )}
        </form.Field>
      </div>

      {/* Baseline Section */}
      <div className="border rounded-lg p-4 bg-slate-50 dark:bg-slate-900">
        <div className="space-y-4">
          <form.Field name="isBaseline">
            {(field) => (
              <div className="flex items-center gap-3">
                <Checkbox
                  id="isBaseline"
                  checked={field.state.value}
                  onCheckedChange={(checked) =>
                    field.handleChange(checked === true)
                  }
                />
                <Label
                  htmlFor="isBaseline"
                  className="font-medium cursor-pointer"
                >
                  {tp('changeOrders.form.createBaselineOnRelease')}
                </Label>
              </div>
            )}
          </form.Field>

          <form.Field name="isBaseline">
            {(isBaselineField) =>
              isBaselineField.state.value && (
                <form.Field name="baselineName">
                  {(field) => (
                    <FormField
                      label={tc('fields.baselineName')}
                      required
                      error={field.state.meta.errors[0]}
                      helpText={tp('changeOrders.form.baselineNameHelp')}
                    >
                      <Input
                        name={field.name}
                        value={field.state.value}
                        onChange={(e) => field.handleChange(e.target.value)}
                        onBlur={field.handleBlur}
                        placeholder={tp('changeOrders.form.baselineNamePlaceholder')}
                        error={!!field.state.meta.errors.length}
                      />
                    </FormField>
                  )}
                </form.Field>
              )
            }
          </form.Field>

          <p className="text-sm text-muted-foreground">
            {tp('changeOrders.form.baselineSectionHelp')}
          </p>
        </div>
      </div>

      {/* Custom Attributes */}
      <AttributesEditor
        value={attributes}
        onChange={setAttributes}
        disabled={isSubmitting}
      />

      {/* Form Actions */}
      <div className="flex justify-end gap-3 pt-4 border-t">
        {onCancel && (
          <Button
            type="button"
            variant="outline"
            onClick={onCancel}
            disabled={isSubmitting}
          >
            {tc('actions.cancel')}
          </Button>
        )}
        <Button
          type="submit"
          disabled={isSubmitting}
          data-testid="change-order-submit"
        >
          {isSubmitting
            ? tc('actions.saving')
            : changeOrder?.id
              ? tp('changeOrders.form.updateSubmit')
              : tp('changeOrders.form.createSubmit')}
        </Button>
      </div>
    </form>
  )
}
